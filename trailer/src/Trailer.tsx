import React from "react";
import { AbsoluteFill, Html5Audio, Sequence, interpolate, staticFile } from "remotion";
import { FPS } from "./brand";
import { Sfx, Wipe } from "./components";
import { Subtitles, subsFor } from "./subtitles";
import { Build } from "./scenes/Build";
import { Hook, LogoReveal, Problem } from "./scenes/Intro";
import { Live } from "./scenes/Live";
import { CTA, Features } from "./scenes/Outro";
import { Quiz } from "./scenes/Quiz";
import { Share } from "./scenes/Share";
import VOICE from "./voice.json"; // generated by scripts/voice.py from narration.json

// [component, startFrame, duration] — starts sit on a 120 BPM grid (1 beat = 15 frames).
const SCENES: [React.FC, number, number][] = [
  [Hook, 0, 120],
  [Problem, 120, 180],
  [LogoReveal, 300, 120],
  [Build, 420, 270],
  [Share, 690, 180],
  [Live, 870, 300],
  [Quiz, 1170, 210],
  [Features, 1380, 210],
  [CTA, 1590, 210],
];
export const TOTAL = 1800;

// "Ramp It Up" (Mixkit #69, ~120 BPM): its drop at 16.1s lands on the logo reveal at 10.0s.
const MUSIC_OFFSET = Math.round(6.1 * FPS);

const voiceAt = (f: number) => VOICE.some((v) => f >= v.at * FPS - 4 && f <= (v.at + v.dur) * FPS + 4);
const musicVolume = (f: number) => {
  // Smooth duck: average the "voice active" flag over ±6 frames so the bed eases down/up.
  let on = 0;
  for (let d = -6; d <= 6; d++) on += voiceAt(f + d) ? 1 : 0;
  const duck = 1 - 0.7 * (on / 13);
  const fade = interpolate(f, [0, 8, TOTAL - 45, TOTAL], [0, 1, 1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
  return 0.5 * duck * fade;
};

const SUBS = subsFor(VOICE, (v) => v.at * FPS);

export const Trailer: React.FC = () => (
  <AbsoluteFill style={{ background: "#000" }}>
    {SCENES.map(([Scene, from, dur], i) => (
      <Sequence key={i} from={from} durationInFrames={dur}>
        <Scene />
      </Sequence>
    ))}
    {/* indigo wipes on every act change after the dark intro */}
    {SCENES.slice(2).map(([, from]) => (
      <Sequence key={`w${from}`} from={from - 10} durationInFrames={20}>
        <Wipe />
        <Sfx s="whoosh" at={0} v={0.8} />
      </Sequence>
    ))}
    <Subtitles subs={SUBS} />
    {VOICE.map((v) => (
      <Sequence key={v.id} from={Math.round(v.at * FPS)} layout="none">
        <Html5Audio src={staticFile(`voice/${v.id}.wav`)} volume={1} />
      </Sequence>
    ))}
    <Html5Audio src={staticFile("audio/music.mp3")} trimBefore={MUSIC_OFFSET} volume={musicVolume} />
  </AbsoluteFill>
);
